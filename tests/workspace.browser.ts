import {chromium,expect} from "@playwright/test";
import assert from "node:assert/strict";
import {spawn} from "node:child_process";
import {mkdtempSync,rmSync,mkdirSync} from "node:fs";
import {join} from "node:path";
import {tmpdir} from "node:os";
import {randomBytes} from "node:crypto";
import {createStore} from "../server/store.ts";
const dir=mkdtempSync(join(tmpdir(),"workspace-browser-"));
const store=createStore(dir),sid=randomBytes(32).toString("hex");
store.db.prepare("INSERT INTO sessions VALUES(?,?)").run(sid,Date.now()+600000);
store.db.close();
mkdirSync("outputs",{recursive:true});
const origin="http://localhost:3105";
const server=spawn(process.execPath,["--import","tsx","server/index.ts"],{env:{...process.env,DATA_DIR:dir,PORT:"3105",APP_URL:origin,NODE_ENV:"production"},stdio:"pipe"});
let browser:Awaited<ReturnType<typeof chromium.launch>>|undefined;
try {
  for(let i=0;i<100;i++){try{if((await fetch(origin+"/api/session")).ok)break;}catch{}await new Promise(r=>setTimeout(r,100));}
  browser=await chromium.launch({...(process.env.CHROMIUM_PATH?{executablePath:process.env.CHROMIUM_PATH}:{}),headless:true,args:["--no-sandbox"]});
  const context=await browser.newContext({viewport:{width:1440,height:1000}});
  const page=await context.newPage(), errors:string[]=[];
  page.on("pageerror",e=>errors.push(e.message));
  await page.goto(origin+"/workspace");
  await page.getByRole("heading",{name:"내 글을 쓰고 보관하는 곳"}).waitFor();
  await context.addCookies([{name:"session",value:sid,domain:"localhost",path:"/",httpOnly:true,sameSite:"Lax"}]);
  await page.reload();
  await page.getByRole("button",{name:"새 폴더 만들기",exact:true}).click();
  await page.getByLabel("새 폴더 이름").fill("웹사이트 만들기");
  await page.getByRole("button",{name:"폴더 만들기",exact:true}).click();
  await page.getByRole("link",{name:"웹사이트 만들기",exact:true}).click();
  await page.getByRole("button",{name:"+ 새 기록",exact:true}).first().click();
  await page.getByLabel("기록 제목").fill("내가 만든 AI 작업실");
  await page.getByLabel("나만 보는 작업 메모").fill("## 작업 과정\n\n검색과 파일 보관을 만들었습니다.\n\n## 확인한 점\n\n새로 접속해도 남아 있어요.");
  await expect(page.locator(".note-save-state")).toContainText("저장됨");
  const path=new URL(page.url()).pathname;
  await page.getByLabel("작업 파일 붙이기").setInputFiles([{name:"작업기록.md",mimeType:"text/markdown",buffer:Buffer.from("# file content")},{name:"instructions.txt",mimeType:"text/plain",buffer:Buffer.from("instructions")}]);
  await expect(page.locator(".note-asset")).toHaveCount(2);
  await expect(page.locator(".note-save-state")).toContainText("저장됨");
  await page.getByRole("button",{name:"☆ 즐겨찾기",exact:true}).click();
  await expect(page.locator(".note-save-state")).toContainText("저장됨");
  await page.getByRole("button",{name:"읽는 모습",exact:true}).click();
  await page.locator(".note-markdown").getByRole("heading",{name:"작업 과정"}).waitFor();
  await page.screenshot({path:"outputs/workspace-note-desktop.png",fullPage:true});
  const cookies=await context.cookies();
  await context.close();
  const second=await browser.newContext({viewport:{width:390,height:844}});
  await second.addCookies(cookies);
  const reopened=await second.newPage();
  await reopened.goto(origin+path);
  await expect(reopened.getByLabel("나만 보는 작업 메모")).toContainText("새로 접속해도");
  await expect(reopened.locator(".note-asset")).toHaveCount(2);
  assert.equal(await reopened.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await reopened.screenshot({path:"outputs/workspace-note-mobile.png",fullPage:true});
  await reopened.getByRole("button",{name:"폴더·메뉴 펼치기"}).click();
  await reopened.getByRole("navigation",{name:"내 기록 분류"}).getByRole("link",{name:/모든 기록/}).click();
  await reopened.getByRole("searchbox").fill("파일 보관");
  await expect(reopened.locator(".workspace-page-row")).toHaveCount(1);
  await reopened.setViewportSize({width:1440,height:1000});
  await reopened.screenshot({path:"outputs/workspace-list-desktop.png",fullPage:true});
  await reopened.locator(".workspace-page-row").click();
  await reopened.getByRole("button",{name:"보관함에 넣기",exact:true}).click();
  await expect(reopened.locator(".note-save-state")).toContainText("저장됨");
  await reopened.getByRole("link",{name:/보관함/}).click();
  await expect(reopened.locator(".workspace-page-row")).toHaveCount(1);
  await reopened.locator(".workspace-page-row").click();
  await reopened.getByRole("button",{name:"보관함에서 꺼내기",exact:true}).click();
  await expect(reopened.locator(".note-save-state")).toContainText("저장됨");
  await reopened.getByRole("link",{name:"공개할 내용 정리하기 →"}).click();
  assert.match(reopened.url(),/\/admin\/records\/[^/]+\/edit$/);
  const guest=await browser.newContext();
  const outsider=await guest.newPage();
  await outsider.goto(origin+path);
  await outsider.getByRole("heading",{name:"내 글을 쓰고 보관하는 곳"}).waitFor();
  assert.deepEqual(await (await guest.request.get(origin+"/api/records")).json(),[]);
  assert.deepEqual(errors,[]);
  console.log("PASS workspace: auth, folders, autosave, files, reopened browser, private notes, search, favorites, archive, mobile, publication handoff");
} finally {
  await browser?.close();server.kill();
  if(server.exitCode===null)await new Promise(resolve=>server.once("exit",resolve));
  rmSync(dir,{recursive:true,force:true});
}
